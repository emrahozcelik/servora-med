// Named disposable guest only. The START_INTENT below is explicitly synthetic:
// it prepares the real ExecStartPre denial boundary, not deployment acceptance.
import test, {before, beforeEach, after} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync, readdirSync, existsSync, mkdirSync, unlinkSync, symlinkSync} from 'node:fs';
import {spawnSync, execFileSync} from 'node:child_process';
import {setup, reset, restore, fault, write, ctl, fixtureTime, readOnlySnapshot, assertImmutable} from './forward-host-systemd-fixture.mjs';
import {fixture} from './forward-host-fixture.mjs';
import {runForwardHost, validateHostLog} from '../scripts/forward-host-driver.mjs';
import {PATHS} from '../scripts/forward-host.mjs';
import {canonical, openHostJournal, publishExclusive} from '../scripts/forward-host-storage.mjs';
import {digest} from '../scripts/forward-host-evidence.mjs';

let saved, authorization;
before(() => { saved = setup(); });
beforeEach(() => { authorization = reset(saved); });
after(() => { if (saved) restore(saved); });

test('FWTIME-01 UNKNOWN denies fresh root admission with no deployment-state mutation', () => {
  const before = readOnlySnapshot();
  const result = fault('forced-time-unknown', 'preflight');
  assert.equal(result.status, 1); assert.match(result.stderr, /TRUSTED_TIME_UNKNOWN/);
  assert.deepEqual(readOnlySnapshot(), before);
  assert.equal(existsSync(PATHS.owner), false); assertImmutable(saved);
});

test('FWTIME-02 initial admission reads the exact sealed legacy collector module', () => {
  const before = readOnlySnapshot(), result = fault('trace-time-reader', 'preflight');
  assert.match(result.stderr, /FIXTURE_TIME_READER=\/usr\/local\/libexec\/servora-med\/trusted-time\.mjs/);
  if (result.status !== 0) assert.match(result.stderr, /TRUSTED_TIME_UNKNOWN/);
  assert.deepEqual(readOnlySnapshot(), before); assertImmutable(saved);
});

async function prepareSyntheticStartIntent() {
  const a = authorization, f = fixture(), originalContext = f.io.context, originalEffect = f.io.effect;
  const pid = Number(ctl('show', 'servora-med.service', '-p', 'MainPID', '--value'));
  const stat = readFileSync('/proc/' + pid + '/stat', 'utf8');
  const oldIdentity = {pid, startTime: stat.slice(stat.lastIndexOf(')') + 2).split(' ')[19],
    bootId: readFileSync('/proc/sys/kernel/random/boot_id', 'utf8').trim(),
    invocationId: ctl('show', 'servora-med.service', '-p', 'InvocationID', '--value')};
  const authorizationSha256 = digest(canonical(a)); let running = true;
  Object.assign(f.authorization, a);
  f.io.now = () => new Date().toISOString().replace(/\.\d{3}Z$/, 'Z');
  f.io.authorizationTime = async () => fixtureTime();
  f.io.toolHash = JSON.parse(readFileSync(PATHS.tool + '/manifest.json')).hash;
  f.io.context = async () => {
    const context = await originalContext();
    return {...context, authorizationSha256, host: {...context.host,
      releaseSha: a.old.releaseSha, artifactSha256: a.old.artifactSha256}};
  };
  f.io.identity = async () => running ? oldIdentity : null;
  f.io.effect = async (...args) => {
    const result = await originalEffect(...args);
    if (args[0] === 'STOP') running = false;
    return result;
  };
  f.io.append = record => {
    f.log.push(structuredClone(record));
    if (record.event === 'START_INTENT') throw new Error('SYNTHETIC_PENDING_START');
  };
  await assert.rejects(runForwardHost(f.io, f.authorization, 'apply'), /SYNTHETIC_PENDING_START/);
  const state = validateHostLog(f.log, a, authorizationSha256, f.io.toolHash);
  assert.equal(state.starts, 1); assert.equal(state.pending.event, 'START_INTENT');
  const attempt = PATHS.root + '/' + a.attemptId;
  mkdirSync(attempt + '/journal', {recursive: true, mode: 0o700});
  const journal = openHostJournal(attempt + '/journal');
  for (const record of f.log) journal.append(record);

  // Fixture preparation only. This never substitutes for OLD-stop/backup/
  // artifact acceptance; those records above were generated by synthetic ports.
  ctl('stop', 'servora-med.service');
  const owner = {attemptId: a.attemptId, approvalSha256: authorizationSha256};
  publishExclusive(PATHS.owner, canonical(owner)); publishExclusive(PATHS.barrier, canonical(owner));
  write(PATHS.guard, '[Service]\nExecStartPre=+/usr/bin/node ' + PATHS.tool + '/forward-host.mjs start-gate\nReadWritePaths=' + PATHS.root + ' /run/servora-med-forward\n');
  write(PATHS.policy, '[Service]\nRestart=no\n');
  mkdirSync('/etc/systemd/system/servora-med-time-evidence@.service.d', {recursive: true, mode: 0o755});
  write(PATHS.collectorDropin, '[Service]\nExecStart=\nExecStart=/usr/bin/node --no-addons ' + PATHS.tool + '/trusted-time.mjs --collect-chrony\n');
  unlinkSync(PATHS.current); symlinkSync('/opt/servora-med/releases/' + a.target.releaseSha, PATHS.current);
  write(PATHS.env, saved.env.replace(/^SERVORA_RELEASE_SHA=.*$/m, 'SERVORA_RELEASE_SHA=' + a.target.releaseSha), 0o640);
  execFileSync('/usr/bin/chown', ['root:servora-med', PATHS.env]);
  for (const path of ['/run/servora-med-forward', '/run/servora-med-recovery']) mkdirSync(path, {recursive: true, mode: 0o700});
  publishExclusive(PATHS.ticket, canonical({attemptId: a.attemptId, authorizationSha256,
    intentHash: state.pending.hash, slot: 1, bootId: oldIdentity.bootId}));
  publishExclusive(PATHS.permit, canonical({attemptId: a.attemptId, authorizationSha256, intentHash: state.pending.hash}));
  ctl('daemon-reload');
  return {attempt, journal, original: journal.read(), authorizationSha256, toolHash: f.io.toolHash};
}

test('FWTIME-03 real systemd ExecStartPre denies UNKNOWN without consuming or resetting its slot', async () => {
  const prepared = await prepareSyntheticStartIntent();
  assert.equal(ctl('is-active', 'chrony.service'), 'active');
  ctl('stop', 'chrony.service'); // Disposable-only fault; collector itself stays active.
  try {
    for (let n = 0; n < 2; n++) {
      const start = spawnSync('/usr/bin/flock', ['-n', PATHS.state + '/host.lock', '/usr/bin/systemctl', 'start', 'servora-med.service'], {encoding: 'utf8', timeout: 20000});
      assert.notEqual(start.status, 0);
      assert.equal(ctl('show', 'servora-med.service', '-p', 'MainPID', '--value'), '0');
      assert.equal(readdirSync(prepared.attempt).filter(name => /^start-\d+\.json$/.test(name)).length, 0);
      assert.deepEqual(prepared.journal.read(), prepared.original);
    }
    const logs = execFileSync('/usr/bin/journalctl', ['-u', 'servora-med.service', '-n', '20', '--no-pager', '-o', 'cat'], {encoding: 'utf8'});
    assert.match(logs, /TRUSTED_TIME_UNKNOWN/);
    assert.equal(validateHostLog(prepared.journal.read(), authorization, prepared.authorizationSha256, prepared.toolHash).starts, 1);
    assert.equal(ctl('show', 'servora-med.service', '-p', 'Restart', '--value'), 'no');
    assert.equal(existsSync(PATHS.owner), true); assert.equal(existsSync(PATHS.barrier), true);
    assertImmutable(saved);
  } finally { ctl('start', 'chrony.service'); }
});
